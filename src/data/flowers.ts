const SEASON_BY_MONTH: Record<number, Season> = {
  0: 'Winter',
  1: 'Winter',
  2: 'Spring',
  3: 'Spring',
  4: 'Spring',
  5: 'Summer',
  6: 'Summer',
  7: 'Summer',
  8: 'Autumn',
  9: 'Autumn',
  10: 'Autumn',
  11: 'Winter',
};

export function getDayOfYear(date: Date): number {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

export function getSeasonForDate(date: Date): Season {
  return SEASON_BY_MONTH[date.getMonth()] ?? 'Autumn';
}

/**
 * Deterministic "Flower of the Day" selector:
 * Prioritizes the current astronomical/calendar season so Today's Bloom
 * always resonates with the actual time of year outside the window,
 * rotating smoothly day by day across seasonal specimens.
 */
export function getFlowerForDate(date: Date): FlowerSpecimen {
  const season = getSeasonForDate(date);
  const seasonalPool = FLOWERS.filter((f) => f.season === season);
  const pool = seasonalPool.length > 0 ? seasonalPool : FLOWERS;
  const dayNumber = getDayOfYear(date);
  // Day 322 (Nov 18) % 7 === 0 -> Winter Camellia (Plate I).
  const index = dayNumber % pool.length;
  return pool[index];
}

export function getFlowerById(id: string): FlowerSpecimen | undefined {
  return FLOWERS.find((f) => f.id === id);
}

export function formatEditorialDate(date: Date): string {
  return date.toLocaleDateString('en-US', {
    weekday: 'long',
    month: 'long',
    day: 'numeric',
    year: 'numeric',
  });
}

export function isSameCalendarDay(a: Date, b: Date): boolean {
  return (
    a.getFullYear() === b.getFullYear() &&
    a.getMonth() === b.getMonth() &&
    a.getDate() === b.getDate()
  );
}
